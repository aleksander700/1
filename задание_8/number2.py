'''**2.** Все пятибуквенные слова, составленные из букв А, К, Ц, Е, Н, Т, записаны в алфавитном порядке и пронумерованы.
Вот начало списка:
1. AAAAA
2. AAAAE
3. ААААК
4. ААААН
5. AAAAT
6. ААААЦ
Определите, под каким номером в этом списке стоит первое слово с чётным номером, которое не начинается с букв А, Е или К и при этом содержит в своей записи не менее двух букв Ц.
Примечание. Слово - последовательность идущих подряд букв, не обязательносмысленная.'''
from itertools import *
i = 0
for el in product(sorted('акцент') , repeat=5):
    i += 1
    word = ''.join(el)
    if i % 2 == 0 and word[0] not in 'аек' and word.count('ц') >= 2:
        print(i)
        break
