"""Виктор составляет таблицу кодовых слов для передачи сообщений,
каждому сообщению соответствует своё кодовое слово.
В качестве кодовых слов Виктор использует 5-буквенные слова, в которых могут быть только буквы Д, Г, И, А, Ш, Э, причём слово не должно начинаться с гласной и не должно заканчиваться согласной.
Сколько различных кодовых слов может использовать Виктор?"""
from itertools import *
count = 0

for el in product('дгиашэ', repeat=5):
    number = ''.join(el)
    if number[0] not in 'иаэ' and number[4] not in 'дгш':
        count += 1
print(count)
