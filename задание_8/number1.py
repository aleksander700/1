'''**1.** Все шестибуквенные слова, составленные из букв П, Л, А, Н, Е. Р, записаны в алфавитном порядке и пронумерованы.
Вот начало списка:
1. AAAAAA
2. AAAAAE
3. АААААЛ
4. АААААН
5. АААААП
6. AAAAAP
Определите, под каким номером в этом списке стоит последнее слово с нечётным номером, в записи которого не содержится ни одной из букв П или Р
и при этом имеется ровно две буквы А и ровно одна буква Н.
Примечание. Слово - последовательность идущих подряд букв, не обязательно осмысленная.
'''
from itertools import *
i = 0
for el in product(sorted('ПЛАНЕР') , repeat=6):
    i += 1
    word = ''.join(el)
    if (i % 2) != 0 and ('П' not in word) and ('Р' not in word) and word.count('А') == 2 and word.count('Н') == 1:
        print(i)
